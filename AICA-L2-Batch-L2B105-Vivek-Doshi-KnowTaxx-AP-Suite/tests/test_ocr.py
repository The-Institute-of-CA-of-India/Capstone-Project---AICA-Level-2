import json
from datetime import date
from decimal import Decimal
from pathlib import Path

import pytest

from app.invoices import ocr_engine as ocr
from app.invoices.ocr_engine import extract_invoice_data, parse_date, parse_invoice_text, repair_gstin

SAMPLES = Path(__file__).parent / "sample_invoices"
EXPECTED = json.loads((SAMPLES / "expected.json").read_text(encoding="utf-8")) if (SAMPLES / "expected.json").exists() else []
needs_tesseract = pytest.mark.skipif(not ocr.find_tesseract(), reason="Tesseract is not installed")

TEXT = """Bharat Engineering Works
12 Station Road, Nashik
GSTIN: 27AAPFU0939F1ZV
TAX INVOICE
Invoice No: BEW/2026/118   Date: 05-10-2026
Due Date: 04/11/2026
Bill To: ABC Manufacturing Pvt Ltd
GSTIN: 27AABCA1234C1Z5
Description  HSN  Qty  Rate  Amount
Repair of motor  998713  2  5,000.00  10,000.00
Taxable Value 10,000.00
CGST @ 9%  900.00
SGST @ 9%  900.00
Grand Total  11,800.00
"""


def test_parse_clean_text():
    r = parse_invoice_text(TEXT, exclude_gstin="27AABCA1234C1Z5")
    assert r["gstin"] == "27AAPFU0939F1ZV"
    assert r["invoice_number"] == "BEW/2026/118"
    assert r["invoice_date"] == date(2026, 10, 5)
    assert r["due_date"] == date(2026, 11, 4)
    assert r["taxable_amount"] == Decimal("10000.00")
    assert r["cgst"] == Decimal("900.00") and r["sgst"] == Decimal("900.00") and r["igst"] is None
    assert r["total_amount"] == Decimal("11800.00")
    assert r["vendor_name"] == "Bharat Engineering Works"
    assert r["arithmetic_ok"] is True
    assert r["confidence"] >= 0.8
    assert r["pan"] == "AAPFU0939F"
    assert r["line_items"][0]["hsn_sac"] == "998713"


def test_buyer_gstin_not_taken_as_seller():
    text = "Bill To: Buyer Co\nGSTIN: 27AABCA1234C1Z5\nSeller: Vendor Co\nGrand Total 100.00"
    r = parse_invoice_text(text, exclude_gstin="27AABCA1234C1Z5")
    assert r["gstin"] is None


def test_arithmetic_failure_lowers_confidence():
    text = "Vendor Name Ltd\nInvoice No: A1\nDate: 01/10/2026\nTaxable Value 1,000.00\nCGST 90.00\nSGST 90.00\nGrand Total 5,000.00"
    r = parse_invoice_text(text)
    assert r["arithmetic_ok"] is False
    assert r["field_confidence"]["total_amount"] < 0.5
    assert any("Arithmetic" in w for w in r["warnings"])


def test_total_derived_when_missing():
    r = parse_invoice_text("Vendor Name Ltd\nTaxable Value 1,000.00\nIGST @ 18% 180.00")
    assert r["total_amount"] == Decimal("1180.00")
    assert r["igst"] == Decimal("180.00")


def test_percent_not_mistaken_for_amount():
    r = parse_invoice_text("Co Name\nTaxable Value 500.00\nCGST 9%\nCGST 45.00\nSGST 9% 45.00\nGrand Total 590.00")
    assert r["cgst"] == Decimal("45.00") and r["sgst"] == Decimal("45.00")


@pytest.mark.parametrize("token,expected", [
    ("05/10/2026", date(2026, 10, 5)), ("05-10-2026", date(2026, 10, 5)), ("05.10.2026", date(2026, 10, 5)),
    ("5-Oct-2026", date(2026, 10, 5)), ("05 October 2026", date(2026, 10, 5)), ("05/10/26", date(2026, 10, 5)),
    ("31/02/2026", None), ("not a date", None), ("05/10/1890", None),
])
def test_dates(token, expected):
    assert parse_date(token) == expected


def test_gstin_ocr_repair():
    assert repair_gstin("27AAPFU0939F1ZV") == ("27AAPFU0939F1ZV", True)
    assert repair_gstin("Z7AAPFU0939F1ZV") == ("27AAPFU0939F1ZV", True)
    assert repair_gstin("27AAPFUO939F1ZV") == ("27AAPFU0939F1ZV", True)
    assert repair_gstin("27AAPFU0939F12V") == ("27AAPFU0939F1ZV", True)


def test_auto_category_and_tds():
    assert ocr.suggest_category("Professional fees for audit") == "Professional Fees"
    assert ocr.suggest_tds("consultancy charges") == ("194J", Decimal("10"))
    assert ocr.suggest_tds("monthly rent for premises")[0] == "194I"
    assert ocr.suggest_tds("steel sheets") == (None, None)


def test_keywords_match_whole_words_only():
    assert ocr.suggest_tds("current account and parent company") == (None, None)
    assert ocr.suggest_category("current account, cable, restraint") is None
    assert ocr.suggest_category("advertising campaign") == "Marketing"
    assert ocr.suggest_category("Spares for machine") == "Repairs & Maintenance"


def test_category_read_from_line_items_not_footer():
    text = TEXT.replace("Repair of motor", "MS Steel Sheets") + "\nGenerated by accounting software. Rent office address."
    r = parse_invoice_text(text)
    assert r["category"] == "Raw Materials" and r["tds_section"] is None


def test_missing_tesseract_degrades_gracefully(monkeypatch, tmp_path):
    monkeypatch.setattr(ocr, "find_tesseract", lambda: None)
    r = extract_invoice_data(tmp_path / "whatever.png")
    assert r["confidence"] == 0 and "not installed" in r["warnings"][0]


@needs_tesseract
def test_corrupt_image_does_not_raise(tmp_path):
    bad = tmp_path / "bad.png"
    bad.write_bytes(b"\x89PNG\r\n\x1a\nbroken")
    r = extract_invoice_data(bad)
    assert r["confidence"] == 0 and r["warnings"]


@needs_tesseract
@pytest.mark.parametrize("row", EXPECTED, ids=[r["file"] for r in EXPECTED])
def test_sample_documents(row):
    r = extract_invoice_data(SAMPLES / row["file"], exclude_gstin=row.get("buyer_gstin"))
    assert r["gstin"] == row["gstin"], r["raw_text"]
    assert r["invoice_number"] == row["number"], r["raw_text"]
    assert r["invoice_date"].isoformat() == row["date"], r["raw_text"]
    assert float(r["total_amount"]) == row["total"], r["raw_text"]
    assert float(r["taxable_amount"]) == row["taxable"], r["raw_text"]
    assert r["vendor_name"] == row["vendor"], r["raw_text"]
    assert r["arithmetic_ok"] is True
    assert r["confidence"] >= 0.8
